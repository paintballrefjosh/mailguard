#!/usr/bin/env python3
"""
MailGuard compound-rule milter.

Postfix header_checks / body_checks are line-oriented PCRE maps: each pattern
tests ONE header or ONE body line in isolation, so they can never express a
condition that spans different parts of a message (e.g. "From: is gmail.com
AND the body mentions a subscription renewal"). Amavis/SpamAssassin *can*
combine fields, but it runs post-queue — by then Postfix has already answered
250 OK, so a SpamAssassin verdict can only bounce/quarantine, never refuse the
message at the SMTP layer.

A milter is the one place that sees the envelope sender, the headers AND the
decoded body *within the live SMTP session*, and can return a hard 5xx REJECT
at end-of-DATA so the message is never queued or delivered — exactly the
behaviour of today's body_checks REJECT, but with multi-condition AND logic.

Rules come from /mailguard/maps-dynamic/compound_rules.json, generated by the
backend from the `rules` table (rows whose conditions JSON has an "all" array).
The file is hot-reloaded on mtime change — no restart needed when rules change.

Fail-open everywhere: if a rule file is missing/bad or anything throws, the
message is ACCEPTed. Postfix is also configured with milter_default_action=
accept so a dead milter never blocks mail.
"""
import os
import re
import sys
import json
import html

import Milter

RULES_FILE = os.environ.get("MG_RULES_FILE", "/mailguard/maps-dynamic/compound_rules.json")
MILTER_SOCKET = os.environ.get("MG_MILTER_SOCKET", "inet:8894@0.0.0.0")
MILTER_NAME = "mailguardcompound"

# Fields a condition may reference. Values are resolved per-message in eom().
KNOWN_FIELDS = {"header_from_domain", "header_from", "subject", "body", "sender_domain"}
# Only 'block' produces an SMTP reject at the milter stage. Other actions
# (quarantine/flag) require post-queue machinery and are ignored here.
ENFORCED_ACTIONS = {"block"}

_HTML_TAG_RE = re.compile(r"<[^>]+>")
_WS_RE = re.compile(r"\s+")


def log(msg):
    sys.stderr.write("[milter] %s\n" % msg)
    sys.stderr.flush()


# ── Rule loading (hot-reloaded on file mtime change) ──────────────────────────
_cache = {"mtime": None, "rules": []}


def _compile_rule(raw):
    """Validate + precompile one rule dict. Returns a normalised rule or None."""
    try:
        rid = int(raw["id"])
    except (KeyError, ValueError, TypeError):
        return None
    action = str(raw.get("action", "block")).lower()
    if action not in ENFORCED_ACTIONS:
        return None
    conds_in = raw.get("conditions") or []
    if not isinstance(conds_in, list) or not conds_in:
        return None
    conds = []
    for c in conds_in:
        field = c.get("field")
        op = (c.get("op") or "regex").lower()
        value = c.get("value")
        if field not in KNOWN_FIELDS or value is None:
            return None  # unknown field -> skip whole rule (fail closed on rules, open on mail)
        if op == "regex":
            try:
                value = re.compile(value, re.IGNORECASE)
            except re.error as e:
                log("rule %d: bad regex %r (%s) - skipping rule" % (rid, c.get("value"), e))
                return None
        elif op in ("eq", "contains"):
            value = str(value).lower()
        else:
            log("rule %d: unknown op %r - skipping rule" % (rid, op))
            return None
        conds.append({"field": field, "op": op, "value": value})
    return {
        "id": rid,
        "action": action,
        "reason": str(raw.get("reason") or raw.get("name") or "Blocked by MailGuard rule"),
        "conditions": conds,
    }


def load_rules():
    try:
        mtime = os.stat(RULES_FILE).st_mtime
    except OSError:
        if _cache["rules"]:
            log("rule file gone - clearing rules")
        _cache["rules"] = []
        _cache["mtime"] = None
        return _cache["rules"]
    if mtime == _cache["mtime"]:
        return _cache["rules"]
    try:
        with open(RULES_FILE) as fh:
            data = json.load(fh)
        rules = [r for r in (_compile_rule(x) for x in (data or [])) if r]
        _cache["rules"] = rules
        _cache["mtime"] = mtime
        log("loaded %d enforceable compound rule(s) from %s" % (len(rules), RULES_FILE))
    except Exception as e:
        log("rule load failed (%s) - keeping %d cached rule(s)" % (e, len(_cache["rules"])))
    return _cache["rules"]


# ── Helpers ───────────────────────────────────────────────────────────────────
def _as_text(v):
    if isinstance(v, bytes):
        return v.decode("utf-8", "replace")
    return v if v is not None else ""


def _domain_of(addr_field):
    """Extract the domain from a From-style header value or bare address."""
    from email.utils import parseaddr
    addr = parseaddr(_as_text(addr_field))[1]
    if "@" in addr:
        return addr.rsplit("@", 1)[1].strip().lower()
    return ""


def _strip_html(text):
    return html.unescape(_HTML_TAG_RE.sub(" ", text))


class MailGuardMilter(Milter.Base):
    def __init__(self):
        self.env_from_domain = ""
        self.from_header = ""
        self.subject = ""
        self.headers = []          # [(name, value)]
        self.body_chunks = []      # [bytes]
        self.authenticated = False

    # -- envelope sender ------------------------------------------------------
    @Milter.noreply
    def envfrom(self, mailfrom, *unused):
        self.env_from_domain = _domain_of(mailfrom)
        # Skip authenticated submissions (local users) entirely.
        auth = self.getsymval("{auth_authen}")
        self.authenticated = bool(auth)
        return Milter.CONTINUE

    # -- headers --------------------------------------------------------------
    @Milter.noreply
    def header(self, name, value):
        name_l = _as_text(name).lower()
        value = _as_text(value)
        self.headers.append((_as_text(name), value))
        if name_l == "from" and not self.from_header:
            self.from_header = value
        elif name_l == "subject" and not self.subject:
            self.subject = value
        return Milter.CONTINUE

    # -- body chunks ----------------------------------------------------------
    @Milter.noreply
    def body(self, chunk):
        if chunk:
            self.body_chunks.append(chunk if isinstance(chunk, bytes) else chunk.encode("utf-8", "replace"))
        return Milter.CONTINUE

    # -- end of message: evaluate rules --------------------------------------
    def eom(self):
        try:
            if self.authenticated:
                return Milter.ACCEPT
            rules = load_rules()
            if not rules:
                return Milter.ACCEPT

            body_text = self._decoded_body()
            values = {
                "header_from_domain": _domain_of(self.from_header),
                "header_from": self.from_header,
                "subject": self.subject,
                "body": body_text,
                "sender_domain": self.env_from_domain,
            }

            for rule in rules:
                if self._matches(rule, values):
                    reason = "[mailguard:crule_id=%d] %s" % (rule["id"], rule["reason"])
                    # Postfix logs this reply text; the log shipper greps the tag.
                    self.setreply("550", "5.7.1", reason[:400])
                    log("REJECT rule %d from_hdr=%r env=%r" % (
                        rule["id"], values["header_from_domain"], values["sender_domain"]))
                    return Milter.REJECT
            return Milter.ACCEPT
        except Exception as e:
            log("eom error (%s) - failing open (ACCEPT)" % e)
            return Milter.ACCEPT

    # -- matching -------------------------------------------------------------
    @staticmethod
    def _matches(rule, values):
        for c in rule["conditions"]:
            fv = _as_text(values.get(c["field"], ""))
            op, val = c["op"], c["value"]
            if op == "regex":
                if not val.search(fv):
                    return False
            elif op == "eq":
                if fv.strip().lower() != val:
                    return False
            elif op == "contains":
                if val not in fv.lower():
                    return False
            else:
                return False
        return True

    def _decoded_body(self):
        """Reconstruct the message and return concatenated decoded text.

        Matches on BOTH the MIME-decoded text parts (so base64/quoted-printable
        and HTML-obfuscated spam is caught, unlike raw body_checks) AND the raw
        body as a fallback.
        """
        raw_body = b"".join(self.body_chunks)
        raw_text = raw_body.decode("utf-8", "replace")
        parts = [raw_text]
        try:
            import email
            hdr = "".join("%s: %s\r\n" % (n, v) for n, v in self.headers)
            msg = email.message_from_bytes(hdr.encode("utf-8", "replace") + b"\r\n" + raw_body)
            for part in msg.walk():
                ctype = part.get_content_type()
                if ctype not in ("text/plain", "text/html"):
                    continue
                payload = part.get_payload(decode=True)
                if not payload:
                    continue
                charset = part.get_content_charset() or "utf-8"
                try:
                    text = payload.decode(charset, "replace")
                except (LookupError, TypeError):
                    text = payload.decode("utf-8", "replace")
                if ctype == "text/html":
                    text = _strip_html(text)
                parts.append(text)
        except Exception as e:
            log("body decode error (%s) - using raw body only" % e)
        return _WS_RE.sub(" ", "\n".join(parts))


def main():
    Milter.factory = MailGuardMilter
    # We never modify the message — only accept/reject. No CHGBODY/CHGHDRS flags.
    Milter.set_flags(0)
    load_rules()
    log("starting on %s (rules=%s)" % (MILTER_SOCKET, RULES_FILE))
    Milter.runmilter(MILTER_NAME, MILTER_SOCKET, timeout=120)
    log("stopped")


if __name__ == "__main__":
    main()
