// Generates Postfix header_checks and body_checks from the blocklists table
// and asks the postfix container to reload its config.
//
// Files are written to /mailguard/maps-dynamic/, which is bind-mounted into
// the postfix container at /etc/postfix/maps-dynamic/. main.cf points
// header_checks/body_checks at that path.
//
// Action mapping:
//   block      -> REJECT 5.7.1 ...   (sender gets 5xx during DATA)
//   quarantine -> HOLD               (queued under hold/, visible in queue UI)
//   flag       -> WARN               (delivers, but reason logged so the
//                                     shipper can mark the event as 'flag')
//   allow      -> skipped            (no override needed at SMTP time)
//
// The "[mailguard:rule_id=N]" tag in the reason is what the log shipper
// greps for to increment hits and attribute the event to the rule.

const fs   = require('fs').promises;
const path = require('path');
const http = require('http');
const db   = require('./db');

const MAPS_DIR    = process.env.POSTFIX_MAPS_DYNAMIC || '/mailguard/maps-dynamic';
const HEADER_FILE = path.join(MAPS_DIR, 'header_checks');
const BODY_FILE   = path.join(MAPS_DIR, 'body_checks');
const SENDER_WL_FILE = path.join(MAPS_DIR, 'sender_whitelist');
const POSTFIX_CONTAINER = process.env.POSTFIX_CONTAINER || 'mailguard-postfix';

const ACTION_VERB = {
  block:      'REJECT 5.7.1',
  quarantine: 'HOLD',
  flag:       'WARN',
};

// Postfix PCRE tables are CASE-INSENSITIVE BY DEFAULT and the trailing
// "i" flag TOGGLES that off. So we deliberately emit patterns WITHOUT a
// trailing flag — that gives case-insensitive matching, which is what
// users almost always want. (See `man 5 pcre_table`.)
const HEADER_FILE_HEADER =
`# Generated by MailGuard backend from the blocklists table.
# DO NOT EDIT — changes are overwritten on every rule mutation.
# Format: /pcre/  ACTION  [mailguard:rule_id=N] reason
# (Postfix PCRE is case-insensitive by default — no /i flag needed.)
`;

const BODY_FILE_HEADER = HEADER_FILE_HEADER;

const SENDER_WL_HEADER =
`# Generated by MailGuard backend from the blocklists table.
# DO NOT EDIT — changes are overwritten on every rule mutation.
# Sender domains with action=allow. Checked in recipient_restrictions
# before postgrey, so a hit short-circuits greylist + RBL checks.
# Format: /@domain.tld$/  OK
# (Postfix PCRE is case-insensitive by default — no /i flag needed.)
`;

// Build a PCRE pattern that matches a sender envelope address whose domain
// equals the given user-supplied domain (case-insensitive). Subdomains do
// not match by default — add a separate rule for "*.domain.tld" if needed.
function senderDomainPattern(rawDomain) {
  let d = String(rawDomain || '').trim().toLowerCase();
  if (!d) return null;
  // Allow a leading "*." wildcard for "any subdomain of"
  let wildcard = false;
  if (d.startsWith('*.')) { wildcard = true; d = d.slice(2); }
  // Escape regex metacharacters in the domain literal.
  const escaped = d.replace(/[.+?^${}()|[\]\\]/g, '\\$&');
  return wildcard ? `@(?:[^.]+\\.)*${escaped}$` : `@${escaped}$`;
}

// Strip a leading "(?i)" since we apply the postfix-native /i flag on the
// whole pattern. Strip user-supplied delimiters and trailing flags. Also
// escape any unescaped forward slashes so the wrapping /.../ delimiters in
// the postfix map line stay unambiguous.
function normalisePattern(raw) {
  let p = String(raw || '').trim();
  if (p.startsWith('(?i)')) p = p.slice(4);
  const m = p.match(/^\/(.+)\/([a-z]*)$/);
  if (m) p = m[1];
  // Escape unescaped slashes: (?<!\\)/ -> \/
  p = p.replace(/(^|[^\\])\//g, '$1\\/');
  return p;
}

// Reduce a free-text reason to something safe for a single Postfix map line.
function sanitiseReason(comment, fallback) {
  const raw = (comment && String(comment).trim()) || fallback;
  return raw
    .replace(/[\r\n]+/g, ' ')
    .replace(/\s+/g, ' ')
    .slice(0, 200);
}

function formatSubjectLine(rule) {
  const verb = ACTION_VERB[rule.action];
  if (!verb) return null;
  const body = normalisePattern(rule.value);
  if (!body) return null;
  const reason = sanitiseReason(rule.comment, 'Subject blocked by MailGuard');
  // No /i — postfix PCRE is case-insensitive by default; /i would toggle it OFF.
  return `/^Subject:.*${body}/  ${verb} [mailguard:rule_id=${rule.id}] ${reason}`;
}

function formatFromLine(rule) {
  const verb = ACTION_VERB[rule.action];
  if (!verb) return null;
  const body = normalisePattern(rule.value);
  if (!body) return null;
  const reason = sanitiseReason(rule.comment, 'From-address blocked by MailGuard');
  return `/^From:.*${body}/  ${verb} [mailguard:rule_id=${rule.id}] ${reason}`;
}

function formatBodyLine(rule) {
  const verb = ACTION_VERB[rule.action];
  if (!verb) return null;
  const body = normalisePattern(rule.value);
  if (!body) return null;
  const reason = sanitiseReason(rule.comment, 'Body blocked by MailGuard');
  return `/${body}/  ${verb} [mailguard:rule_id=${rule.id}] ${reason}`;
}

async function ensureDir() {
  await fs.mkdir(MAPS_DIR, { recursive: true });
}

async function regenerateRules() {
  await ensureDir();
  const [rows] = await db.query(
    `SELECT id, list_type, value, action, comment
       FROM blocklists
      WHERE enabled = 1
        AND (
          (list_type IN ('regex_subject','regex_body','from_email')
             AND action IN ('block','quarantine','flag'))
          OR
          (list_type = 'domain' AND action = 'allow')
        )
      ORDER BY id ASC`
  );

  const headerLines  = [HEADER_FILE_HEADER];
  const bodyLines    = [BODY_FILE_HEADER];
  const wlLines      = [SENDER_WL_HEADER];
  let subjectCount = 0, fromCount = 0, wlCount = 0;

  let skipped = 0;
  for (const r of rows) {
    if (r.list_type === 'domain' && r.action === 'allow') {
      const pat = senderDomainPattern(r.value);
      if (!pat) { skipped++; continue; }
      wlLines.push(`/${pat}/  OK   # rule_id=${r.id} ${sanitiseReason(r.comment, '')}`.trimEnd());
      wlCount++;
      continue;
    }

    // Validate the regex before writing it — a bad pattern will make
    // postfix refuse to load the whole map.
    try { new RegExp(normalisePattern(r.value)); }
    catch { skipped++; continue; }

    if (r.list_type === 'regex_subject') {
      const line = formatSubjectLine(r);
      if (line) { headerLines.push(line); subjectCount++; }
    } else if (r.list_type === 'from_email') {
      const line = formatFromLine(r);
      if (line) { headerLines.push(line); fromCount++; }
    } else if (r.list_type === 'regex_body') {
      const line = formatBodyLine(r);
      if (line) bodyLines.push(line);
    }
  }

  await fs.writeFile(HEADER_FILE,    headerLines.join('\n') + '\n', 'utf8');
  await fs.writeFile(BODY_FILE,      bodyLines.join('\n')   + '\n', 'utf8');
  await fs.writeFile(SENDER_WL_FILE, wlLines.join('\n')     + '\n', 'utf8');

  return {
    subject_rules:   subjectCount,
    from_rules:      fromCount,
    body_rules:      bodyLines.length - 1,
    whitelist_rules: wlCount,
    skipped,
  };
}

// Talk to the docker socket and run `postfix reload` inside the postfix
// container. Returns true on success, false otherwise (never throws — the
// rules on disk are still authoritative; reload is best-effort).
function dockerExec(container, cmd) {
  return new Promise((resolve, reject) => {
    const payload = JSON.stringify({
      AttachStdout: true, AttachStderr: true, Tty: false, Cmd: cmd,
    });
    const req = http.request({
      socketPath: '/var/run/docker.sock',
      path:       `/containers/${container}/exec`,
      method:     'POST',
      headers: {
        'Content-Type':   'application/json',
        'Content-Length': Buffer.byteLength(payload),
      },
    }, res => {
      let body = '';
      res.setEncoding('utf8');
      res.on('data', c => body += c);
      res.on('end', () => {
        if (res.statusCode !== 201) {
          return reject(new Error(`exec create ${res.statusCode}: ${body}`));
        }
        try {
          const { Id } = JSON.parse(body);
          const start = http.request({
            socketPath: '/var/run/docker.sock',
            path:       `/exec/${Id}/start`,
            method:     'POST',
            headers: { 'Content-Type': 'application/json' },
          }, sres => { sres.resume(); sres.on('end', () => resolve()); });
          start.on('error', reject);
          start.end(JSON.stringify({ Detach: false, Tty: false }));
        } catch (e) { reject(e); }
      });
    });
    req.on('error', reject);
    req.end(payload);
  });
}

async function reloadPostfix() {
  try {
    await dockerExec(POSTFIX_CONTAINER, ['postfix', 'reload']);
    return true;
  } catch (e) {
    console.warn(`[postfix-rules] reload failed: ${e.message}`);
    return false;
  }
}

// Convenience: regenerate + reload. Reload errors are swallowed.
async function syncRules() {
  const stats = await regenerateRules();
  const reloaded = await reloadPostfix();
  return { ...stats, reloaded };
}

module.exports = { regenerateRules, reloadPostfix, syncRules };
